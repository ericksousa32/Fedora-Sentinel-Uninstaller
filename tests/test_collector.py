def _report(home: Path, runner: FakeRunner, desktop_dir: Path) -> ScanReport:
    return Collector(home=home, runner=runner, desktop_dirs=[desktop_dir]).collect()


def _collect(home: Path, runner: FakeRunner, desktop_dir: Path) -> dict[str, Candidate]:
    report = _report(home, runner, desktop_dir)
    return {str(c.path.relative_to(home)): c for c in report.candidates}


def _snapshot(root: Path) -> dict[str, tuple[int, int, float, bytes | str]]:
    """Full picture of a tree: mode, size, mtime and content/target."""
    state: dict[str, tuple[int, int, float, bytes | str]] = {}
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        for name in dirnames + filenames:
            path = Path(dirpath) / name
            info = path.lstat()
            if path.is_symlink():
                content: bytes | str = str(path.readlink())
            elif path.is_file():
                content = path.read_bytes()
            else:
                content = b""
            state[str(path)] = (info.st_mode, info.st_size, info.st_mtime, content)
    return state


def test_scoring(populated_home: Path, fake_runner: FakeRunner, desktop_dir: Path) -> None:
    found = _collect(populated_home, fake_runner, desktop_dir)

    flatpak = found[".var/app/org.gimp.GIMP"]
    assert (flatpak.score, flatpak.action) == (0.95, Action.QUARANTINE)
    assert flatpak.category is Category.FLATPAK

    hexchat = found[".config/hexchat"]
    assert (hexchat.score, hexchat.action) == (0.85, Action.QUARANTINE)
    assert hexchat.matched_name == "hexchat"
    assert hexchat.size_bytes == 100

    assert found[".local/share/kwebkitpart"].score == 0.85

    # KConfig variant: "kolourpaintrc" -> removed package "kolourpaint"
    kolourpaint = found[".config/kolourpaintrc"]
    assert (kolourpaint.score, kolourpaint.matched_name) == (0.80, "kolourpaint")
    assert "via 'kolourpaint'" in kolourpaint.evidence[0].detail

    assert found[".config/kunifiedpush-org.kde.neochat"].score == 0.80

    # Launcher points to an AppImage that no longer exists
    photocraft = found[".config/photocraft"]
    assert (photocraft.score, photocraft.action) == (0.75, Action.QUARANTINE)
    assert photocraft.evidence[0].source == "appimage"

    nuget = found[".local/share/NuGet"]
    assert (nuget.score, nuget.matched_name) == (0.80, "dotnet-runtime-8.0")
    assert "owned by removed package" in nuget.evidence[0].detail

    aspnet = found[".config/aspnetcore"]
    assert aspnet.action is Action.QUARANTINE_WITH_SNAPSHOT
    assert aspnet.matched_name == "aspnetcore-runtime-8.0"

    mystery = found[".cache/mystery"]
    assert (mystery.score, mystery.action) == (0.20, Action.LIST_ONLY)

    # Never candidates:
    for relative in (
        ".config/GIMP",  # gimp reinstalled
        ".config/kdenlive",  # installed
        ".config/dolphinrc",  # installed, via KConfig variant
        ".cache/mozilla",  # owned by installed firefox
        ".config/Code",  # via .desktop
        ".config/LM Studio",  # AppImage in use
        ".local/share/wget",  # owner wget2-wget installed
        ".config/katevirc",  # owner kf6-ktexteditor installed
        ".config/KDE",  # protected
        ".var/app/com.spotify.Client",  # installed Flatpak
        ".var/app/com.google.Chrome",  # Plasma Browser Integration stub
        ".var/app/io.gitlab.librewolf-community",
        ".var/app/org.mozilla.firefox",
        ".config/dconf",  # protected
        ".local/share/fsu",  # FSU quarantine
        ".ssh",  # out of scope
    ):
        assert relative not in found, relative

    scores = [c.score for c in found.values()]
    assert scores == sorted(scores, reverse=True)


def test_report_counters(populated_home: Path, fake_runner: FakeRunner, desktop_dir: Path) -> None:
    report = _report(populated_home, fake_runner, desktop_dir)
    protected = {str(p.relative_to(populated_home)) for p in report.protected_skipped}
    assert protected == {
        ".config/dconf",
        ".config/KDE",
        ".local/share/fsu",
        ".local/share/applications",
    }
    # GIMP, kdenlive, dolphinrc, mozilla, Code, LM Studio, wget, katevirc, Spotify
    assert report.installed_skipped == 9
    assert {p.name for p in report.regenerated_skipped} == {
        "com.google.Chrome",
        "io.gitlab.librewolf-community",
        "org.mozilla.firefox",
    }
    assert [p.name for p in report.stale_launchers] == ["ai.storyteller.photocraft.desktop"]
    assert len(report.warnings) == 1
    assert "Plasma Browser Integration" in report.warnings[0]
    assert set(report.timings) >= {"rpm", "dnf5_history", "scan_and_score"}


def test_stub_with_real_data_is_a_candidate(home: Path, fake_runner: FakeRunner) -> None:
    app = home / ".var/app/org.chromium.Chromium"
