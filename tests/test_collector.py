PBI_HOST = "#!/bin/sh\n# Automatically generated by plasma-browser-integration-flatpak-integrator\n"


def _make(path: Path, size: int = 10) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(b"x" * size)


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _pbi_stub(app_dir: Path, manifest_dir: str | None) -> None:
    """Folder as created by Plasma Browser Integration for a Flatpak browser."""
    _write(app_dir / "plasma-browser-integration-host", PBI_HOST)
    if manifest_dir:
        _write(app_dir / manifest_dir / "org.kde.plasma.browser_integration.json", "{}")


